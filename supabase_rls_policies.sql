-- ------------------------------------------------------------------------------
-- 3. HABILITACIÓN DE REALTIME EN SUPABASE (PUBLICACIÓN REACTIVA)
-- ------------------------------------------------------------------------------
-- Asegurar que las réplicas contengan la información completa para DIFF en tiempo real
ALTER TABLE clients REPLICA IDENTITY FULL;
ALTER TABLE planes REPLICA IDENTITY FULL;
ALTER TABLE dietas REPLICA IDENTITY FULL;
ALTER TABLE finances REPLICA IDENTITY FULL;
ALTER TABLE metricas_evolucion REPLICA IDENTITY FULL;

-- Agregar tablas a la publicación de Supabase Realtime
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' AND tablename = 'clients'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE clients, planes, dietas, finances, metricas_evolucion;
  END IF;
EXCEPTION
  WHEN OTHERS THEN
    NULL; -- Si la publicación no existe o ya está agregada, continuar
END $$;

