    OR (
      (auth.jwt() -> 'user_metadata' ->> 'role') IN ('coach', 'admin')
      AND gym_id = (auth.jwt() -> 'user_metadata' ->> 'gym_id')
    )
  )
  WITH CHECK (
    user_id = auth.uid()
    OR (
      (auth.jwt() -> 'user_metadata' ->> 'role') IN ('coach', 'admin')
      AND gym_id = (auth.jwt() -> 'user_metadata' ->> 'gym_id')
    )
