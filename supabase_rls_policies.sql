-- Atleta: solo ve planes donde el client_id coincide con su registro
CREATE POLICY "athletes_select_own_planes" ON planes
  FOR SELECT
  USING (
    client_id IN (
      SELECT id FROM clients
      WHERE auth_user_id = auth.uid() OR email = (auth.jwt() ->> 'email')
    )
  );

